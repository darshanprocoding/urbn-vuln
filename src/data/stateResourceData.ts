// Helper to compute national aggregate totals
export function getNationalResourceSummary(states: StateResourceProfile[] = STATE_RESOURCE_DATA) {
  const summary: Record<keyof StateResourceProfile['resources'], { total: number; active: number; inReserve: number; inMaintenance: number }> = {
    waterTankers: { total: 0, active: 0, inReserve: 0, inMaintenance: 0 },
    rationPackets: { total: 0, active: 0, inReserve: 0, inMaintenance: 0 },
    floatingClinics: { total: 0, active: 0, inReserve: 0, inMaintenance: 0 },
    debrisMachinery: { total: 0, active: 0, inReserve: 0, inMaintenance: 0 },
    emergencyGenerators: { total: 0, active: 0, inReserve: 0, inMaintenance: 0 },
    tarpTentKits: { total: 0, active: 0, inReserve: 0, inMaintenance: 0 },
    waterMotorPumps: { total: 0, active: 0, inReserve: 0, inMaintenance: 0 },
  };

  let totalSDRFBattalions = 0;
  let totalPopulationCovered = 0;

  for (const state of states) {
    totalSDRFBattalions += state.sdrfBattalions;
    totalPopulationCovered += state.population;
    for (const key of Object.keys(summary) as (keyof typeof summary)[]) {
      summary[key].total += state.resources[key].total;
      summary[key].active += state.resources[key].active;
      summary[key].inReserve += state.resources[key].inReserve;
      summary[key].inMaintenance += state.resources[key].inMaintenance;
    }
  }

  return {
    summary,
    totalStates: states.length,
    totalSDRFBattalions,
    totalPopulationCovered,
  };
}
