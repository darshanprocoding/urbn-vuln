// Great-circle Haversine distance in Kilometers
export function calculateDistanceKm(
  coord1: [number, number] | any, // [lng, lat]
  coord2: [number, number] | any  // [lng, lat]
): number {
  const c1 = Array.isArray(coord1) && coord1.length >= 2 ? coord1 : [78.9629, 20.5937];
  const c2 = Array.isArray(coord2) && coord2.length >= 2 ? coord2 : [78.9629, 20.5937];

  const lon1 = typeof c1[0] === 'number' ? c1[0] : 78.9629;
  const lat1 = typeof c1[1] === 'number' ? c1[1] : 20.5937;
  const lon2 = typeof c2[0] === 'number' ? c2[0] : 78.9629;
  const lat2 = typeof c2[1] === 'number' ? c2[1] : 20.5937;

  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Find closest warehouse to a target [lng, lat] point (optionally within a state)
export function findNearestWarehouse(
  targetCoords: [number, number],
  stateIdFilter?: string
): { warehouse: WarehouseFacility; distanceKm: number } {
  let candidates = WAREHOUSE_FACILITIES;
  if (stateIdFilter) {
    const stateCandidates = WAREHOUSE_FACILITIES.filter(
      (w) =>
        w.stateId === stateIdFilter ||
        w.state.toLowerCase() === stateIdFilter.toLowerCase()
    );
    if (stateCandidates.length > 0) {
      candidates = stateCandidates;
    }
  }

  let nearest = candidates[0];
  let minDistance = calculateDistanceKm(targetCoords, nearest.coordinates);

  for (let i = 1; i < candidates.length; i++) {
    const dist = calculateDistanceKm(targetCoords, candidates[i].coordinates);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = candidates[i];
    }
  }

  return { warehouse: nearest, distanceKm: Math.round(minDistance * 10) / 10 };
}

// Get all warehouses in a given state or UT
export function getWarehousesForState(stateNameOrId: string): WarehouseFacility[] {
  const norm = stateNameOrId.toLowerCase().trim();
  const matched = WAREHOUSE_FACILITIES.filter(
    (w) =>
      w.stateId === norm ||
      w.state.toLowerCase().includes(norm) ||
      norm.includes(w.state.toLowerCase())
  );
  return matched.length > 0 ? matched : WAREHOUSE_FACILITIES;
}
